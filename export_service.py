"""Export Service for generating Plain Text and PDF reports.

Provides formatting functions to download simplified research abstracts as TXT or PDF files.
"""

from __future__ import annotations

import unicodedata
from datetime import datetime
from typing import List
from fpdf import FPDF
from fpdf.enums import XPos, YPos
from ai_service import DifficultTerm, SimplificationResult


def sanitize_text_for_pdf(text: str) -> str:
    """Sanitize unicode text for standard PDF core fonts (latin-1 compatible).

    Replaces common typographic quotes, dashes, symbols, and accents.
    """
    replacements = {
        "\u2014": " - ",   # em dash
        "\u2013": " - ",   # en dash
        "\u2018": "'",     # left single quote
        "\u2019": "'",     # right single quote
        "\u201c": '"',     # left double quote
        "\u201d": '"',     # right double quote
        "\u2022": "*",     # bullet
        "\u2026": "...",   # ellipsis
        "\u03a9": "Omega",  # greek omega
        "\u00b2": "2",     # superscript 2
        "\u00b3": "3",     # superscript 3
        "\u00d7": "x",     # multiplication sign
    }
    for orig, rep in replacements.items():
        text = text.replace(orig, rep)

    # Normalize to closest ASCII representation where possible
    normalized = unicodedata.normalize("NFKD", text)
    encoded = normalized.encode("latin-1", "replace").decode("latin-1")
    return encoded


def generate_txt_report(
    original_abstract: str,
    result: SimplificationResult,
    model_name: str = "Google Gemini",
) -> str:
    """Generate a clean, structured plain text report of the simplification."""
    orig_words = len(original_abstract.split())
    simp_words = len(result.simplified_abstract.split())
    date_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    divider = "=" * 80
    sub_divider = "-" * 80

    lines = [
        divider,
        "RESEARCH PAPER ABSTRACT SIMPLIFIER - ACADEMIC REPORT",
        "Problem Statement PS7 | Final Year BTech CSE Mini Project",
        f"Generated On: {date_str} | AI Model: {model_name}",
        divider,
        "",
        "1. ORIGINAL ABSTRACT",
        f"(Word Count: {orig_words} words)",
        sub_divider,
        original_abstract.strip(),
        "",
        "2. SIMPLIFIED ABSTRACT (Beginner-Friendly Explanation)",
        f"(Word Count: {simp_words} words | Reduction: {max(0, 100 - int(simp_words * 100 / max(1, orig_words)))}%)",
        sub_divider,
        result.simplified_abstract.strip(),
        "",
        "3. KEY TAKEAWAYS",
        sub_divider,
    ]

    for idx, takeaway in enumerate(result.key_takeaways, 1):
        lines.append(f"  {idx}. {takeaway.strip()}")

    lines.extend([
        "",
        "4. DIFFICULT TECHNICAL TERMS & MEANINGS",
        sub_divider,
        f"{'Technical Term':<32} | {'Simple Beginner Meaning'}",
        sub_divider,
    ])

    for item in result.difficult_terms:
        lines.append(f"{item.term:<32} | {item.meaning}")

    lines.extend([
        "",
        divider,
        "End of Report - Generated by Research Paper Abstract Simplifier (PS7)",
        divider,
    ])

    return "\n".join(lines)


class AcademicReportPDF(FPDF):
    """Custom styled PDF document for academic report."""

    def header(self):
        self.set_fill_color(30, 58, 138)  # Deep Indigo / Blue
        self.rect(0, 0, 210, 14, "F")
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(255, 255, 255)
        self.set_xy(10, 3)
        self.cell(
            self.epw,
            8,
            "PS7: Research Paper Abstract Simplifier | Final Year BTech CSE Mini Project",
            align="C",
            new_x=XPos.LMARGIN,
            new_y=YPos.NEXT,
        )
        self.ln(5)

    def footer(self):
        self.set_y(-14)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(128, 128, 128)
        self.cell(
            self.epw,
            8,
            f"Page {self.page_no()}/{{nb}} - Generated via Google Gemini API",
            align="C",
            new_x=XPos.LMARGIN,
            new_y=YPos.NEXT,
        )


def generate_pdf_report(
    original_abstract: str,
    result: SimplificationResult,
    model_name: str = "Google Gemini",
) -> bytes:
    """Generate an attractive academic PDF report using fpdf2."""
    pdf = AcademicReportPDF(orientation="P", unit="mm", format="A4")
    pdf.alias_nb_pages()
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.set_margins(15, 18, 15)
    pdf.add_page()

    epw = pdf.epw

    # Document Title
    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(30, 41, 59)  # Slate-800
    pdf.cell(
        epw,
        9,
        "Research Paper Abstract Simplification Report",
        new_x=XPos.LMARGIN,
        new_y=YPos.NEXT,
    )

    # Metadata subtitle
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(100, 116, 139)  # Slate-500
    date_str = datetime.now().strftime("%B %d, %Y - %H:%M:%S")
    pdf.cell(
        epw,
        5,
        f"Date: {date_str}  |  AI Model: {sanitize_text_for_pdf(model_name)}",
        new_x=XPos.LMARGIN,
        new_y=YPos.NEXT,
    )
    pdf.ln(4)

    # Section 1: Original Abstract
    pdf.set_fill_color(241, 245, 249)  # Slate-100
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(30, 58, 138)
    orig_words = len(original_abstract.split())
    pdf.cell(
        epw,
        7,
        f" 1. Original Abstract ({orig_words} words)",
        fill=True,
        new_x=XPos.LMARGIN,
        new_y=YPos.NEXT,
    )
    pdf.ln(2)

    pdf.set_font("Helvetica", "", 9.5)
    pdf.set_text_color(51, 65, 85)
    clean_orig = sanitize_text_for_pdf(original_abstract.strip())
    pdf.multi_cell(epw, 5, clean_orig)
    pdf.ln(4)

    # Section 2: Simplified Abstract
    simp_words = len(result.simplified_abstract.split())
    pdf.set_fill_color(238, 242, 255)  # Indigo-50
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(67, 56, 202)  # Indigo-700
    pdf.cell(
        epw,
        7,
        f" 2. Simplified Abstract ({simp_words} words)",
        fill=True,
        new_x=XPos.LMARGIN,
        new_y=YPos.NEXT,
    )
    pdf.ln(2)

    pdf.set_font("Helvetica", "", 9.5)
    pdf.set_text_color(30, 41, 59)
    clean_simp = sanitize_text_for_pdf(result.simplified_abstract.strip())
    pdf.multi_cell(epw, 5, clean_simp)
    pdf.ln(4)

    # Section 3: Key Takeaways
    pdf.set_fill_color(243, 244, 246)
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(17, 24, 39)
    pdf.cell(
        epw,
        7,
        " 3. Key Takeaways",
        fill=True,
        new_x=XPos.LMARGIN,
        new_y=YPos.NEXT,
    )
    pdf.ln(2)

    pdf.set_font("Helvetica", "", 9.5)
    pdf.set_text_color(51, 65, 85)
    for idx, takeaway in enumerate(result.key_takeaways, 1):
        clean_item = sanitize_text_for_pdf(takeaway.strip())
        pdf.multi_cell(epw, 5, f" -  {clean_item}")
    pdf.ln(4)

    # Section 4: Difficult Technical Terms & Meanings
    pdf.set_fill_color(241, 245, 249)
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(30, 58, 138)
    pdf.cell(
        epw,
        7,
        " 4. Difficult Technical Terms & Meanings",
        fill=True,
        new_x=XPos.LMARGIN,
        new_y=YPos.NEXT,
    )
    pdf.ln(3)

    # Built-in fpdf2 table
    col_widths = (50, epw - 50)
    pdf.set_font("Helvetica", "", 9)
    with pdf.table(col_widths=col_widths, line_height=5.5) as table:
        hdr = table.row()
        hdr.cell("Technical Term")
        hdr.cell("Simple Meaning")

        for item in result.difficult_terms:
            clean_term = sanitize_text_for_pdf(item.term.strip())
            clean_meaning = sanitize_text_for_pdf(item.meaning.strip())
            row = table.row()
            row.cell(clean_term)
            row.cell(clean_meaning)

    return bytes(pdf.output())
